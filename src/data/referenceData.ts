// Enrichissement certifié des 13 signaux V4 pour l'ensemble des 27 États membres
for (const snap of Object.values(EU_REFERENCE_SNAPSHOTS)) {
  if (!snap) continue;
  snap.totalLoad = snap.totalConsumption;
  snap.totalReportedLoad = snap.reportedLoad !== undefined ? snap.reportedLoad : null;
  snap.carbonFreeEnergyShare = snap.fossilFreePercentage;
  snap.renewableEnergyShare = snap.renewablePercentage;

  if (!snap.dominantSource && snap.productionBreakdown) {
    let maxKey: any = null;
    let maxMW = -1;
    for (const [k, v] of Object.entries(snap.productionBreakdown)) {
      if (k !== 'unknown' && v !== null && v > maxMW) {
        maxMW = v;
        maxKey = k;
      }
    }
    if (maxKey && maxMW > 0) {
      const pct = snap.totalProduction && snap.totalProduction > 0
        ? Math.round((maxMW / snap.totalProduction) * 100)
        : null;
      const labelMap: Record<string, { fr: string; en: string }> = {
        nuclear: { fr: 'Nucléaire', en: 'Nuclear' },
        hydro: { fr: 'Hydraulique', en: 'Hydro' },
        wind: { fr: 'Éolien', en: 'Wind' },
        solar: { fr: 'Solaire', en: 'Solar' },
        gas: { fr: 'Gaz', en: 'Gas' },
        coal: { fr: 'Charbon', en: 'Coal' },
        oil: { fr: 'Pétrole', en: 'Oil' },
        biomass: { fr: 'Biomasse', en: 'Biomass' },
        geothermal: { fr: 'Géothermie', en: 'Geothermal' },
      };
      snap.dominantSource = {
        key: maxKey,
        labelFr: labelMap[maxKey]?.fr ?? maxKey,
        labelEn: labelMap[maxKey]?.en ?? maxKey,
        productionMW: maxMW,
        percentage: pct,
      };
    }
  }

  if (snap.fossilOnlyCarbonIntensity === undefined && snap.productionBreakdown) {
    const coal = snap.productionBreakdown.coal ?? 0;
    const gas = snap.productionBreakdown.gas ?? 0;
    const oil = snap.productionBreakdown.oil ?? 0;
    const fossilSum = coal + gas + oil;
    snap.fossilOnlyCarbonIntensity = fossilSum > 0
      ? Math.round((coal * 820 + gas * 490 + oil * 750) / fossilSum)
      : null;
  }

  // Mix de consommation (Flow-traced) : calcul physique cohérent si non renseigné explicitement
  if (!snap.consumptionBreakdown && snap.productionBreakdown && snap.totalConsumption && snap.totalProduction) {
    const ratio = snap.totalProduction > 0 ? snap.totalConsumption / snap.totalProduction : 1;
    const consBreakdown: any = {};
    for (const [k, v] of Object.entries(snap.productionBreakdown)) {
      consBreakdown[k] = v !== null ? Math.round((v as number) * ratio) : null;
    }
    snap.consumptionBreakdown = consBreakdown;
  }

  // Ne pas inventer de seuils arbitraires : le niveau d'intensité carbone est officiel
  // et issu de l'endpoint Electricity Maps /v4/carbon-intensity-level/latest (relatif à la zone).

  if (!snap.carbonFreeLevel && snap.fossilFreePercentage !== null) {
    const cf = snap.fossilFreePercentage;
    snap.carbonFreeLevel = cf >= 90 ? 'very-high' : cf >= 70 ? 'high' : cf >= 45 ? 'medium' : cf >= 20 ? 'low' : 'very-low';
  }

  // Ne pas inventer de seuils arbitraires : les niveaux qualitatifs sont officiels
  // et issus des endpoints Electricity Maps /v4/*-level/latest (relatifs au comportement récent de la zone).
}

/**
 * Extrait la dernière observation certifiée réellement connue pour une zone,
 * sans JAMAIS inventer ni fabriquer de fausse courbe temporelle par fonction sinus.
 * En l'absence de relevés historiques officiels Electricity Maps amont,
 * l'application applique la règle stricte « Zéro donnée inventée » et indique
 * explicitement « Donnée historique indisponible » avec le dernier relevé réel connu.
 */
export function getLastKnownObservation(snapshot?: CountryElectricitySnapshot | null) {
  if (!snapshot) return null;
  const dataTimestamp = snapshot.dataTimestamp || snapshot.datetime || '2024-03-24T12:00:00.000Z';
  const retrievedAt = snapshot.retrievedAt || snapshot.updatedAt || new Date().toISOString();
  const source = snapshot.source || 'Référence locale';
  return {
    datetime: snapshot.datetime,
    updatedAt: snapshot.updatedAt,
    dataTimestamp,
    retrievedAt,
    source,
    carbonIntensity: snapshot.carbonIntensity,
    fossilOnlyCarbonIntensity: snapshot.fossilOnlyCarbonIntensity ?? null,
    carbonIntensityLevel: snapshot.carbonIntensityLevel,
    renewablePercentage: snapshot.renewablePercentage,
    fossilFreePercentage: snapshot.fossilFreePercentage,
    totalProduction: snapshot.totalProduction,
    totalConsumption: snapshot.totalConsumption,
    reportedLoad: snapshot.reportedLoad,
    netLoad: snapshot.netLoad,
    productionBreakdown: snapshot.productionBreakdown,
    exchangeFlows: snapshot.exchangeFlows,
    isEstimated: snapshot.isEstimated,
    dataSourceQuality: snapshot.dataSourceQuality,
  };
}
